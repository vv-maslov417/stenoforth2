\ =====================================================================
\  gui-resize.f - диагностика изменения размера окна
\  Показывает, доходят ли до окна сообщения изменения размера.
\  Рабочий файл: только подгрузка библиотеки и описание формы.
\
\  Запуск:  spf486.exe gui-resize.f
\  Порядок: потянуть мышью за нижнюю границу окна, затем нажать
\           "Обновить" и посмотреть счётчики.
\ =====================================================================

REQUIRE WINDOW gui-kit.f

"Диагностика изменения размера"   WINDOW main 660 260
"Сообщений WM_SIZE:"              TEXT l1 16 16 210 18
"-"                               TEXT v1 230 16 90 18
"Сообщений WM_SIZING:"            TEXT l2 16 40 210 18
"-"                               TEXT v2 230 40 90 18
"Клиент, ширина:"                 TEXT l3 16 64 210 18
"-"                               TEXT v3 230 64 90 18
"Клиент, высота:"                 TEXT l4 340 64 130 18
"-"                               TEXT v4 480 64 90 18
"Обновить"                        BUTTON b1 16 110 160 32 on-upd
"Закрыть"                         BUTTON b2 190 110 160 32 on-quit
END

\ ------------------------------------------------------------ обработчики
: N>STR ( n -- a u ) 0 <# #S #> ;
: SHOW-N { n h } n N>STR h TEXT! ;

: on-upd ( -- )
  SIZEN   @ v1 @ SHOW-N
  SIZINGN @ v2 @ SHOW-N
  CLIENT-W  v3 @ SHOW-N
  CLIENT-H  v4 @ SHOW-N
;

: on-quit ( -- ) QUIT-APP ;

\ ---------------------------------------------------------------- запуск
4 RESIZE-MARGIN          \ края окна легче зацепить мышью
HIDE-CONSOLE
SHOW main
BYE
